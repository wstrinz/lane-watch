export type InterpretationState = "ACTIVE" | "OPEN" | "SUPPORTED" | "PROPOSED" | "UNMEASURED" | "BLOCKED" | "CONTEXT";

export type InterpretationNode = {
  id: string;
  kind: "objective" | "quest" | "decision" | "track" | "claim" | "proposal" | "concept";
  kicker: string;
  title: string;
  summary: string;
  state: InterpretationState;
  trackId?: string;
  why?: string;
  relation?: string;
  evidence?: string[];
  scope?: string[];
  unlocks?: string[];
  metrics?: string[];
  color?: string;
};

